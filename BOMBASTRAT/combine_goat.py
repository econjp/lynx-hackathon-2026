"""BOMBASTRAT + GOAT in one portfolio at different weights. Writes COMBINE_GOAT.md.

    python BOMBASTRAT/combine_goat.py        (about 30 seconds)

Both books are first put on the same constant risk (GOAT's positions are scaled with the same
trailing covariance method BOMBASTRAT uses), then mixed at the position level and scored as one model.
The weight is judged on 1997-2009 only.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path[:0] = [str(ROOT), str(ROOT / "research" / "eemil" / "final_combined")]

import numpy as np
import pandas as pd
import polars as pl

import final_validation as fv
from BOMBASTRAT import bombastrat as bs
from src import goat_model as gm

ev, va = fv.ev, fv.va
DATE, START, END, ERAS, E2 = fv.DATE, fv.START, fv.d[-1], fv.ERAS, fv.E2
ERA = list(ERAS)


def frame(pos):
    p = pos.to_pandas().set_index(DATE)
    p.index = pd.to_datetime(p.index)
    return p


def back(df):
    df = df.copy(); df.index.name = DATE
    return pl.from_pandas(df.reset_index()).with_columns(pl.col(DATE).cast(pl.Date))


def mix(prices, macro, w_goat):
    """w_goat of GOAT + (1 - w_goat) of BOMBASTRAT, each at the same constant risk."""
    px = bs._frame(prices)
    g = bs.exante_scale(frame(gm.goat_positions(prices)), px)        # GOAT at constant book risk
    b = frame(bs.positions(prices, macro))                            # already at constant book risk
    return back(w_goat * g + (1 - w_goat) * b)


def kf(pos, a=START, b=END, keys=("adjusted_sharpe",), prices=fv.prices):
    return ev.calc_key_figures(pos.filter(pl.col(DATE).is_between(a, b)), prices, key_figures=list(keys))


def row(name, pos):
    f = kf(pos, keys=["adjusted_sharpe", "sharpe", "kurtosis", "av_holding", "position_bias"])
    return (name, f["adjusted_sharpe"], kf(pos, START, E2)["adjusted_sharpe"], *[kf(pos, a, b)["adjusted_sharpe"] for a, b in ERAS.values()],
            f["sharpe"], f["kurtosis"], f["av_holding"], f["position_bias"])


def table(header, rows):
    fmt = lambda v: f"{v:.2f}" if isinstance(v, (float, np.floating)) else str(v)
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows])


W = (0.0, 0.2, 0.33, 0.5, 0.67, 0.8, 1.0)
POS = {w: mix(fv.prices, fv.macro, w) for w in W}
label = lambda w: "BOMBASTRAT alone" if w == 0 else "GOAT alone (at constant risk)" if w == 1 else f"{w:.0%} GOAT + {1 - w:.0%} BOMBASTRAT"
head = ["model", "full", f"{START.year}-{E2.year} (choose here)"] + ERA + ["sharpe", "kurt", "holding d", "long tilt"]
t1 = [row(label(w), POS[w]) for w in W] + [row("GOAT as submitted (no risk scaling)", gm.goat_positions(fv.prices))]
best_w = max(W, key=lambda w: kf(POS[w], START, E2)["adjusted_sharpe"])

# Engine 1 of GOAT as a fourth equal-risk forecast inside BOMBASTRAT, instead of mixing two finished books
import engines_bc as eb
f, px, vol = bs.forecasts(fv.prices, fv.macro)
dp = px.diff()


def four(extra):
    parts = {**f, **extra}
    total = sum(parts[s].div(bs.own_risk(parts[s], vol, dp), axis=0).fillna(0.0) for s in parts)
    units = (total / vol).replace([np.inf, -np.inf], np.nan).fillna(0.0)
    return back(bs.glide(bs.exante_scale(units, px), bs.GLIDE).fillna(0.0))


t2 = [row("BOMBASTRAT (3 forecasts)", POS[0.0]),
      row("+ Kristofer stop as a 4th forecast (long only, 10 stocks+bonds)", four({"kris": eb.FC["B"]})),
      row("+ plain holding of the 10 as a 4th forecast (control)", four({"hold": eb.FC["long"]}))]

# robustness of the 50/50
R = pd.DataFrame({w: kf(POS[w], keys=["returns"])["returns"].to_pandas().set_index(DATE)["returns"].iloc[3:] for w in W}).dropna()
idx = va.boot_idx(len(R), n_boot=2000)
B = {w: va.boot_scores(R[w].values, idx) for w in (0.0, 0.5, 1.0)}
q = lambda x: "{:.2f} to {:.2f}".format(*np.nanpercentile(x, [5, 95]))
t3 = [("50/50 minus BOMBASTRAT alone", va.adj_sharpe(R[0.5].values) - va.adj_sharpe(R[0.0].values), q(B[0.5] - B[0.0]), f"{np.nanmean(B[0.5] > B[0.0]):.0%}"),
      ("50/50 minus GOAT alone", va.adj_sharpe(R[0.5].values) - va.adj_sharpe(R[1.0].values), q(B[0.5] - B[1.0]), f"{np.nanmean(B[0.5] > B[1.0]):.0%}")]
roll = lambda r: (r.rolling(780).mean() / r.rolling(780).std() * np.sqrt(260)).dropna()
t4 = [(label(w), roll(R[w]).min(), roll(R[w]).quantile(0.1), f"{(roll(R[w]) > 0.5).mean():.0%}", R[w].groupby(R.index.year).apply(lambda x: x.mean() / x.std()).gt(0).sum()) for w in (0.0, 0.5, 1.0)]
leak = va.leak_test(lambda p: mix(p, fv.macro.filter(pl.col(DATE) <= p[DATE][-1]), 0.5), fv.prices, cuts=(0.3, 0.5, 0.7, 0.9, 0.97))
num = [c for c in fv.prices.columns if c != DATE]

md = f"""# BOMBASTRAT + GOAT in one portfolio

Generated by `BOMBASTRAT/combine_goat.py`, do not edit by hand. Adjusted Sharpe, Lynx evaluator, scored from {START}.
P&L correlation between the two models: {R[0.0].corr(R[1.0]):.2f}.

## Weights

{table(head, t1)}

Best weight on {START.year}-{E2.year}: **{label(best_w)}**.

## Is the 50/50 gain real?

{table(["difference", "adjusted Sharpe", "90% interval (bootstrap)", "P(50/50 is higher)"], t3)}

{table(["model", "worst 3-year window", "10% low 3-year window", "3-year windows above 0.5", f"positive calendar years of {R.index.year.nunique()}"], t4)}

Leak test of the 50/50 (history cut at 30/50/70/90/97%, prices and macro): **{'PASS' if leak[0] else 'FAIL'}** (largest difference {leak[1]:.0e}; GOAT's first 20 days are excluded by the cuts).

## Alternative: one extra forecast instead of two finished books

{table(head, t2)}
"""
(HERE / "COMBINE_GOAT.md").write_text(md, encoding="utf-8")
print(md)
